  function normalize(value) {
    // 아래첨자 ₂·전각 영문도 같은 글자로 맞추고, 공백·구두점 차이를 없앤다.
    return value.normalize('NFKC').toLowerCase().replace(/[\s\p{P}\p{S}]/gu, '');
  }

  function search(query) {
    const textQuery = query.trim();
    const keyword = normalize(textQuery);
    if (textQuery && !keyword) return []; // 기호만 썼다고 전체 용어가 나오지 않게 한다.
    return TERMS.filter((entry) => {
      const text = normalize([entry.term, entry.english, entry.category, ...entry.aliases, entry.meaning, entry.example].join(' '));
      return text.includes(keyword);
    });
  }

  return { CHECKED_ON, SOURCES, TERMS, search };
